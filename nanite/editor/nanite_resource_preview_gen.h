#pragma once

#ifdef TOOLS_ENABLED

#include "editor/inspector/editor_resource_preview.h"
// editor_resource_preview.h forward-declares Texture2D, but the
// GDVIRTUAL3RC_REQUIRED(Ref<Texture2D>, ...) macro in EditorResourcePreviewGenerator
// expands to a static MethodInfo getter that calls
// GetTypeInfo<Ref<Texture2D>>::get_class_info(), which requires the full type.
// Pull in the definition via texture.h (also reachable via image_texture.h).
#include "scene/resources/texture.h"

class NaniteResourcePreviewGenerator : public EditorResourcePreviewGenerator {
	GDCLASS(NaniteResourcePreviewGenerator, EditorResourcePreviewGenerator);

public:
	virtual bool handles(const String &p_type) const override;
	virtual Ref<Texture2D> generate(const Ref<Resource> &p_from, const Size2 &p_size, Dictionary &p_metadata) const override;
};

#endif // TOOLS_ENABLED
